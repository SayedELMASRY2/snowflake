-- ==============================================================================
-- Snowflake Infrastructure Setup & Role-Based Access Control
-- Database: ECOMMERCE_DB
-- Schemas: RAW, STAGING, MARTS
-- Warehouse: ECOMMERCE_WH
-- Role: ACCOUNTADMIN (or DBT_ROLE)
-- ==============================================================================

USE ROLE ACCOUNTADMIN;

-- 1. Create Virtual Warehouse ECOMMERCE_WH
CREATE WAREHOUSE IF NOT EXISTS ECOMMERCE_WH
    WITH WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

-- 2. Create Target Database and Schemas
CREATE DATABASE IF NOT EXISTS ECOMMERCE_DB;
CREATE SCHEMA IF NOT EXISTS ECOMMERCE_DB.RAW;
CREATE SCHEMA IF NOT EXISTS ECOMMERCE_DB.STAGING;
CREATE SCHEMA IF NOT EXISTS ECOMMERCE_DB.MARTS;

-- 3. Create DBT_ROLE and Grant Privileges (Optional RBAC setup)
CREATE ROLE IF NOT EXISTS DBT_ROLE;

-- Grant Warehouse and Database Privileges to DBT_ROLE
GRANT USAGE ON WAREHOUSE ECOMMERCE_WH TO ROLE DBT_ROLE;
GRANT USAGE ON DATABASE ECOMMERCE_DB TO ROLE DBT_ROLE;

-- Grant Schema Privileges to DBT_ROLE
GRANT USAGE ON SCHEMA ECOMMERCE_DB.RAW TO ROLE DBT_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA ECOMMERCE_DB.RAW TO ROLE DBT_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA ECOMMERCE_DB.RAW TO ROLE DBT_ROLE;

GRANT ALL PRIVILEGES ON SCHEMA ECOMMERCE_DB.STAGING TO ROLE DBT_ROLE;
GRANT ALL PRIVILEGES ON SCHEMA ECOMMERCE_DB.MARTS TO ROLE DBT_ROLE;

-- Grant DBT_ROLE to the executing user
GRANT ROLE DBT_ROLE TO USER IDENTIFIER(CURRENT_USER());

-- 4. Create File Format and Internal Stage for Ingestion
USE DATABASE ECOMMERCE_DB;
USE SCHEMA RAW;

CREATE OR REPLACE FILE FORMAT ECOMMERCE_DB.RAW.CSV_INGEST_FORMAT
    TYPE = 'CSV'
    FIELD_DELIMITER = ','
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    NULL_IF = ('', 'NULL', 'null')
    EMPTY_FIELD_AS_NULL = TRUE
    TRIM_SPACE = TRUE
    ERROR_ON_COLUMN_COUNT_MISMATCH = FALSE;

CREATE OR REPLACE STAGE ECOMMERCE_DB.RAW.CSV_STAGE
    FILE_FORMAT = ECOMMERCE_DB.RAW.CSV_INGEST_FORMAT;

-- 5. Create Raw Tables
CREATE TABLE IF NOT EXISTS ECOMMERCE_DB.RAW.CUSTOMERS (
    customer_id     NUMBER(38,0),
    customer_name   VARCHAR(255),
    email           VARCHAR(255),
    city            VARCHAR(255),
    signup_date     DATE
);

CREATE TABLE IF NOT EXISTS ECOMMERCE_DB.RAW.PRODUCTS (
    product_id      NUMBER(38,0),
    product_name    VARCHAR(255),
    category        VARCHAR(100),
    price           NUMBER(10,2)
);

CREATE TABLE IF NOT EXISTS ECOMMERCE_DB.RAW.ORDERS (
    order_id        NUMBER(38,0),
    customer_id     NUMBER(38,0),
    product_id      NUMBER(38,0),
    quantity        VARCHAR(50),
    order_date      DATE,
    status          VARCHAR(50)
);
